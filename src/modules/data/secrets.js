function buildContext(movie, director) {
  return {
    title: movie.title,
    year: movie.year,
    director: director || "el equipo de dirección",
  };
}

function buildFallback(movie, director) {
  const context = buildContext(movie, director);
  const seed = Number(movie.id) || 0;

  return FALLBACK_PHASES.map((phase, index) => {
    const pool = FALLBACK_POOL[phase];
    const template = pool[(seed + index * 7) % pool.length];
    return {
      phase,
      title: pickFallbackTitle(phase, index, context),
      text: template(context),
    };
  });
}

function pickFallbackTitle(phase, index, context) {
  if (phase === "before") {
    return index === 0 ? "Un proyecto que cambió de forma" : "El rodaje que casi no sucede";
  }
  if (phase === "during") {
    return index === 1 ? "La toma que nadie había planeado" : "Un decorado para la historia";
  }
  return index === 3 ? "Lo que el estreno dejó atrás" : `El legado de ${context.title}`;
}

export function getSecrets(movie, { director = null } = {}) {
  const curated = CURATED[Number(movie.id)];
  if (Array.isArray(curated)) return curated;
  return buildFallback(movie, director);
}
